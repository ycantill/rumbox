const BY_SLUG = new Map(CITIES.map((c) => [c.slug, c]));

export function getCity(slug: string | null | undefined): City | undefined {
  return slug ? BY_SLUG.get(slug) : undefined;
}

/** Ciudad más cercana a unas coordenadas (para autocompletar con GPS). */
export function nearestCity(lat: number, lng: number): City {
  let best = CITIES[0];
  let bestKm = Infinity;
  for (const c of CITIES) {
    const km = haversineKm(lat, lng, c.lat, c.lng);
    if (km < bestKm) {
      best = c;
      bestKm = km;
    }
  }
  return best;
}

/** Texto en minúsculas, sin tildes ni signos, para comparar lo que se escribe con los nombres. */
export function simplify(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

const SEARCH_INDEX = CITIES.map((city) => {
  const name = simplify(city.name);
  return { city, name, words: name.split(" "), text: `${name} ${simplify(city.department)}` };
});

/**
 * Municipios que coinciden con lo que la persona escribe, sin importar tildes ni
 * mayúsculas; cada palabra debe estar en el nombre o en el departamento. Salen
 * primero los que empiezan así, luego los que tienen una palabra que empieza así
 * ("buga" → Guadalajara de Buga) y después el resto, cada grupo en orden
 * alfabético. Ninguna región va primero: aún no se sabe dónde será el piloto.
 */
export function searchCities(query: string, limit = 50): City[] {
  const q = simplify(query);
  if (!q) return [];
  const words = q.split(" ");
  const found: { city: City; rank: number }[] = [];
  for (const entry of SEARCH_INDEX) {
    if (!words.every((w) => entry.text.includes(w))) continue;
    const rank = entry.name.startsWith(q) ? 0 : entry.words.some((w) => w.startsWith(words[0])) ? 1 : 2;
    found.push({ city: entry.city, rank });
  }
  found.sort((a, b) => a.rank - b.rank || a.city.name.localeCompare(b.city.name, "es"));
  return found.slice(0, limit).map((f) => f.city);
}

